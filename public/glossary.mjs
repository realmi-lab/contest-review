// 모든 용어를 한 번에 찾는 식. 몇 번째 괄호가 맞았는지로 어떤 용어인지 안다.
const ANY = new RegExp(TERMS.map(([, re]) => `(${re.source})`).join("|"), "gi");

// 글에 나온 용어: [[표기, 풀이], ...] (TERMS 순서)
export const termsIn = (texts) => {
  const all = texts.join(" ");
  return TERMS.filter(([, re]) => re.test(all)).map(([name, , meaning]) => [name, meaning]);
};

// 이미 만든 HTML의 글자 부분(태그 밖)에서 용어마다 처음 나온 곳에 점선 밑줄과 풀이를 단다.
// seen을 여러 번 넘기면 한 화면에서 처음 한 번만 단다.
export function markTerms(html, seen = new Set()) {
  return html
    .split(/(<[^>]+>)/)
    .map((part) =>
      part.startsWith("<")
        ? part
        : part.replace(ANY, (m, ...groups) => {
            const [name, , meaning] = TERMS[groups.findIndex((g) => g !== undefined)];
            if (seen.has(name)) return m;
            seen.add(name);
            return `<abbr class="term" title="${meaning}">${m}</abbr>`;
          }),
    )
    .join("");
}
