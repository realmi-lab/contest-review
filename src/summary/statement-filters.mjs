// 요지 후보 거르기. 판단이 필요 없는 잡음은 모델에 묻기 전에 규칙으로 먼저 뺀다.

// 쪽·장·섹션 구성이나 제출 사실만 설명하는 문장. 모델이 쪽마다 만들어 낼 때가 있다.
// 예) "문서 제목은 'S18'이며…", "참가팀이 제출한 제안서 페이지 22.", "제안서의 2 장은 '데이터 탐색'으로…"
const aboutDocument = [
  /문서\s*제목은|\d+\s*장은|섹션은|작성한\s*문서|제출물(?:인|로서)/u,
  /제출\s*주체는|(?:소개|발표)\s*자료(?:이)?다[.\s]*$/u, // "제출 주체는 … 팀의 서비스 소개 자료다."
  /(?:제안서|문서|자료|보고서|제출물)[^.]{0,30}(?:\d+\s*(?:페이지|쪽)|(?:페이지|쪽)\s*\d+)/u,
  /(?:가지|개)\s*(?:항목|단계)으로\s*구성/u,
  /제출(?:한|된)[^.]{0,40}(?:제안서|자료|문서|보고서|결과|것)(?:\s*(?:페이지|쪽)\s*\d*)?[.\s]*$/u,
  /^.{0,40}(?:\d+\s*(?:페이지|쪽)|(?:페이지|쪽)\s*\d+)[.\s]*$/u, // 쪽 표시만 있는 줄
  /(?:제안서|문서|자료).{0,40}(?:페이지|섹션|슬라이드)[.\s]*$/u, // "…제안서 '2.2 제공 데이터' 페이지."
  // 자료에 무엇이 없다고 모델이 덧붙인 평. 제출자가 밝힌 내용이 아니다.
  // 예) "제공된 원문은 … 구체적인 제안 내용이나 데이터는 포함되어 있지 않습니다.", "제출자는 … 제목만 제시하고 … 설명하지 않았습니다."
  /제공된\s*원문은|원문에는?\s*포함되어\s*있지\s*않/u,
  /(?:제목|명칭|단어)(?:만|를)\s*제시(?:하고|했으나)[^.]*(?:않았습니다|없습니다)/u,
  /인용한\s*것으로\s*보이나/u,
  // 캡처 판독 상태에 대한 모델의 평. 제출자가 밝힌 한계가 아니다.
  // 예) "원문에는 컬럼명 오기나 표 셀이 줄바꿈과 열 구분자로 뒤섞여 있어 … 판독 불확실로 남긴다."
  /판독\s*(?:불확실|불가)|열\s*구분자|OCR/u,
];
export const describesDocument = (text) => aboutDocument.some((re) => re.test(String(text || "")));

// OCR 표 행을 그대로 옮긴 요점("티켓예매수(건) | 1,255,837 | 13.5 | …"). 문장이 아니므로 요지 후보에서 뺀다.
// 열과 값이 짝지어진 표 요약(mode "표의 열·값 대조")은 | 를 쓰지 않아 해당하지 않는다.
export const rawTableRow = (text) => (String(text || "").match(/\|/gu) || []).length >= 2;

// 앞 문장이 있어야 뜻이 통하는 문장("하지만, …", "이를 통해 …"). 혼자 떼어 요지로 쓰면 어색하다.
export const danglingStart = (text) =>
  /^(?:하지만|그러나|그런데|그래서|따라서|그리고|또한|반면|즉|이에|이를|이는|이러한|이처럼)[,，\s]/u.test(String(text || "").trim());

// 그림을 그렸다는 설명만 있고 알아낸 사실이 없는 문장. 결과 후보에서 뺀다.
// 예) "…3 차원 산점도로 시각화했습니다.", "연도별 평균 예매율 추이를 … 나타냄.", "상하시선각도에 따른 3 차원 산점도."
export const describesFigure = (text) =>
  /시각화(?:했|하였|함|한)|(?:추이|분포|관계)를[^.]{0,30}나타(?:냄|낸|냈)|(?:산점도|그래프|히스토그램|차트)[.\s]*$/u.test(String(text || ""));

// 내용 대신 문서를 가리키는 말투를 걷어 낸다. 사실은 그대로 두고 틀만 뗀다.
// 예) "원문 묶음은 …을 다루며, … 추정한다고 적혀 있다." → "…을 다루며, … 추정한다."
//     "… 하위 75% 이상 0.6487로 표시되어 있다." → "… 하위 75% 이상 0.6487이다."
export const plainVoice = (text) => String(text || "")
  .replace(/^원문(?:\s*묶음)?[은는]\s*/u, "")
  .replace(/([다음함])고\s*(?:적혀|표시되어|표기되어|기록되어|기재되어)\s*있다/gu, "$1")
  .replace(/(\d[\d.,]*\s*%?)(?:으)?로\s*(?:표시|표기|기록|기재)되어\s*있다/gu, "$1이다");

// 쪽마다 찍힌 행사명을 문장 앞에 붙인 것을 뗀다. 인용한 줄에 없는 회차 숫자 때문에 근거 대조에서 떨어진다.
// 예) "제 11 회 빅콘테스트 에서 예술의전당 의 좌석 등급을 추정하기 위해 K-means …" → "예술의전당 의 좌석 등급을 …"
export function withoutEventPreamble(text) {
  const rest = String(text || "").replace(/^[^,.]{0,30}?제\s*\d+\s*회\s*[^,.]{0,12}(?:콘테스트|공모전|경진대회|해커톤)[^,.]{0,30}?에서\s+/u, "");
  return rest.length >= 15 ? rest : text;
}

// 핵심 요지 후보가 될 수 없는 요점: 소제목, 표 행 그대로, 앞 문장에 기대는 문장
export const notStatement = (text) => looksLikeHeading(text) || rawTableRow(text) || danglingStart(text);

// 서술어 없이 짧은 소제목·자료 제목. 상세 요약에는 남기되 핵심 요지 후보에서는 뺀다.
// 예) "Customized Regression Model for Airbnb Dynamic Pricing", "공연예술 및 가격 결정 관련 선행 연구/사례 분석"
// 한글 위주는 45자, 영문 위주(논문·자료 제목)는 70자까지 소제목으로 본다.
export function looksLikeHeading(text) {
  const t = String(text || "").trim();
  const hangul = (t.match(/[가-힣]/gu) || []).length;
  return t.length <= (hangul >= t.length * 0.3 ? 45 : 70) && !/\d/u.test(t) &&
    !/(?:[.!?。]|다|요|함|음|됨|임|짐|냄|봄|줌|있음|없음)$/u.test(t);
}

// "자료에 ~가 제시되지 않았다"처럼 무엇이 없다고 단정하는 문장
export const claimsAbsence = (text) =>
  /(?:제시|명시|언급|기재|확인|설명|공개|보고|제공)되(?:지|어\s*있지)\s*않|(?:나타나|드러나|보이)지\s*않|밝히지\s*않|(?:적혀|나와|들어)\s*있지\s*않|원문에\s*없/u.test(text);

// 화면만 보고 짐작한 문장("~로 보인다", "단정하지 않는다"). 사실이 아니라 추측이라 세부 요약에 쓰지 않는다.
export const guesses = (text) => /(?:로|처럼|것으로)\s*보(?:인다|이는|임)|듯하다|(?:단정|확정)(?:하지|되지)\s*않|(?:단정|확정)할\s*수\s*없|추정된다/u.test(text);

// 문장에 적힌 숫자 목록. 천 단위 쉼표는 떼고 소수는 한 덩어리로 본다.
export const digits = (s) => s.normalize("NFKC").replace(/(?<=\d),(?=\d{3}(?:\D|$))/gu, "").match(/\d+(?:\.\d+)?/gu) || [];

// 원문(source)에 적힌 수로 볼 수 있는 값. 점·줄표·쌍점으로 이어 쓴 날짜·시각은 조각으로도 보고(2022.01 → 2022, 1),
// 앞자리 0은 떼며(06 → 6), 연.월 꼴의 두 자리 연도에는 20을 붙인다(21.12 → 2021).
// 글자 인식이 소수점 뒤에 넣은 공백은 없앤다(0. 0928 → 0.0928).
// (실측: '2022년 1월부터' ↔ 원문 '2022.01~', '2021년 12월' ↔ '17.01~21.12'에서 맞는 문장이 수치 대조에 떨어졌다.)
function numberForms(source) {
  const text = source.normalize("NFKC").replace(/(\d)\.\s+(\d)/gu, "$1.$2");
  const forms = new Set(digits(text));
  for (const run of text.match(/\d+/gu) || []) forms.add(String(Number(run)));
  for (const [, year] of text.matchAll(/(?<![\d.])(\d{2})[.\-/](?:0?[1-9]|1[0-2])(?!\d)/gu)) forms.add("20" + year);
  return forms;
}
// 문장(text)의 숫자 가운데 원문(source)에 적혀 있지 않은 것
export function unprintedNumbers(text, source) {
  const forms = numberForms(source);
  return digits(text).filter((n) => !forms.has(n) && (n.includes(".") || !forms.has(String(Number(n)))));
}
